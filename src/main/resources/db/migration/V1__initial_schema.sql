CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE CHECK (email = lower(trim(email))),
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(16) NOT NULL CHECK (role IN ('STUDENT','STAFF','ADMIN')),
    active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    version BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL,
    description VARCHAR(500) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT true,
    version BIGINT NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX categories_name_unique ON categories (lower(name));
CREATE TABLE tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(160) NOT NULL,
    description VARCHAR(5000) NOT NULL,
    category_id BIGINT NOT NULL REFERENCES categories(id),
    creator_id BIGINT NOT NULL REFERENCES app_users(id),
    assignee_id BIGINT REFERENCES app_users(id),
    priority VARCHAR(16) NOT NULL CHECK (priority IN ('LOW','MEDIUM','HIGH')),
    status VARCHAR(16) NOT NULL CHECK (status IN ('OPEN','IN_PROGRESS','RESOLVED','CLOSED')),
    resolution_summary VARCHAR(2000),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    resolved_at TIMESTAMPTZ,
    closed_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT resolution_consistent CHECK (
      (status IN ('RESOLVED','CLOSED') AND resolved_at IS NOT NULL AND length(trim(resolution_summary)) > 0)
      OR (status IN ('OPEN','IN_PROGRESS') AND resolved_at IS NULL AND resolution_summary IS NULL)),
    CONSTRAINT closure_consistent CHECK ((status = 'CLOSED') = (closed_at IS NOT NULL))
);
CREATE INDEX tickets_creator_created_idx ON tickets (creator_id, created_at DESC, id DESC);
CREATE INDEX tickets_assignee_created_idx ON tickets (assignee_id, created_at DESC, id DESC);
CREATE INDEX tickets_status_created_idx ON tickets (status, created_at DESC, id DESC);
CREATE INDEX tickets_category_idx ON tickets(category_id);
CREATE TABLE comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id BIGINT NOT NULL REFERENCES tickets(id),
    author_id BIGINT NOT NULL REFERENCES app_users(id),
    body VARCHAR(2000) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX comments_ticket_idx ON comments (ticket_id, created_at, id);
CREATE TABLE ticket_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id BIGINT NOT NULL REFERENCES tickets(id),
    actor_id BIGINT NOT NULL REFERENCES app_users(id),
    event_type VARCHAR(32) NOT NULL CHECK (event_type IN ('CREATED','ASSIGNED','REASSIGNED','STATUS_CHANGED','REOPENED','COMMENT_CREATED')),
    previous_value VARCHAR(100),
    new_value VARCHAR(100),
    reason VARCHAR(2000),
    created_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX events_ticket_idx ON ticket_events (ticket_id, created_at, id);
-- Protect the audit log even from accidental repository updates/deletes.
CREATE FUNCTION reject_event_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'Ticket event history is append-only'; END;
$$;
CREATE TRIGGER ticket_events_immutable BEFORE UPDATE OR DELETE ON ticket_events
FOR EACH ROW EXECUTE FUNCTION reject_event_mutation();
